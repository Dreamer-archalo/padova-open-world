import assert from 'node:assert/strict';
import fs from 'node:fs';
import {makeRoadGraph,roadRoute,dist} from './dist/core.js';
import {prepareGameplayMap,AIRPORT_GATE,areaLocal,AIRPORT} from './dist/gameplay-areas.js';
const map=JSON.parse(fs.readFileSync(new URL('./dist/data/padova.json',import.meta.url)));
prepareGameplayMap(map);
const graph=makeRoadGraph(map.roads,{separateLevels:true});
const sorio=graph.segments.filter(s=>s.road.n==='Via Sorio'&&s.connected&&!s.road.b&&!s.road.tunnel&&Number(s.road.layer||0)===0);
assert(sorio.length,'Via Sorio has no connected at-grade driving segment');
const candidates=sorio.flatMap(s=>[graph.nodes[s.a],graph.nodes[s.b]]).filter(n=>dist(n,AIRPORT_GATE)>75&&dist(n,AIRPORT_GATE)<1800).sort((a,b)=>dist(a,AIRPORT_GATE)-dist(b,AIRPORT_GATE));
assert(candidates.length,'Via Sorio lacks a practical origin');
const origin=candidates[0];
const outbound=roadRoute(origin,AIRPORT_GATE,graph,{maxMs:5000,maxSteps:200000});
const inbound=roadRoute(AIRPORT_GATE,origin,graph,{maxMs:5000,maxSteps:200000});
assert(outbound.length>=3,'Via Sorio to airport gate cannot be driven');
assert(inbound.length>=3,'Airport gate to Via Sorio cannot be driven');
const entrance=map.gameplay.roads.find(r=>r.n==='Ingresso aeroporto');
assert(entrance?.access==='yes');
const outer=areaLocal(AIRPORT,...entrance.p[0]),inner=areaLocal(AIRPORT,...entrance.p.at(-1));
assert(outer.u>215&&inner.u<215,'Entrance does not cross airport fence at proper location');
console.log('PASS Via Sorio ↔ airport gate on real connected ground-level network',JSON.stringify({outboundPoints:outbound.length,inboundPoints:inbound.length,viaSorioSegments:sorio.length,origin,cityJunction:map.gameplay.airportRoadIntegration.cityJunction}));
