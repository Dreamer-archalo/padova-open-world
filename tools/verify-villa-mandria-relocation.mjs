import assert from 'node:assert/strict';
import fs from 'node:fs';
import {project} from '../dist/core.js';
import {applyCityData} from '../dist/districts.js';
import {prepareGameplayMap,gameplayStructures,gameplaySpawns,VILLA,HOME} from '../dist/gameplay-areas.js';
import {MANDRIA_SEARCH,TREVES_PUBLIC_PARK,VILLA_PUBLIC_NAME} from '../dist/villa-mandria-relocation.js';
import {Terrain} from '../dist/terrain.js';
const read=name=>JSON.parse(fs.readFileSync(new URL(`../dist/data/${name}.json`,import.meta.url)));
const map=read('padova');applyCityData(map,read('city'));
const nearPark=p=>Math.hypot(p[0]-TREVES_PUBLIC_PARK.x,p[1]-TREVES_PUBLIC_PARK.z)<180;
const originalBuildings=map.buildings.filter(b=>b.p.some(nearPark));
const originalFootpaths=map.roads.filter(r=>['footway','path','steps','cycleway'].includes(r.k)&&r.p.some(nearPark));
const originalAreas=map.areas.filter(a=>a.p?.some(nearPark));
const footpathKey=r=>JSON.stringify([r.n,r.k,r.p]);
const originalKeys=new Set(originalFootpaths.map(footpathKey));
prepareGameplayMap(map);
const report=map.gameplay.villaRelocation;
assert(report&&report.name===VILLA_PUBLIC_NAME,'new Mandria location and report must exist');
assert.equal(HOME.name,VILLA_PUBLIC_NAME,'there must be only one named home, in Mandria');
assert(Math.hypot(VILLA.x-MANDRIA_SEARCH.x,VILLA.z-MANDRIA_SEARCH.z)<850,'villa must remain in agreed Mandria–Armistizio search area');
assert(Math.hypot(VILLA.x-TREVES_PUBLIC_PARK.x,VILLA.z-TREVES_PUBLIC_PARK.z)>2200,'estate must leave Treves completely');
assert(originalBuildings.every(b=>map.buildings.includes(b)),'restore every original park building');
assert(originalAreas.every(a=>map.areas.includes(a)),'restore original park area/water features');
const existingKeys=new Set(map.roads.filter(r=>['footway','path','steps','cycleway'].includes(r.k)&&r.p.some(nearPark)).map(footpathKey));
assert([...originalKeys].every(key=>existingKeys.has(key)),'restore every original public footpath segment');
const parkIsClear=p=>Math.hypot(p.x-TREVES_PUBLIC_PARK.x,p.z-TREVES_PUBLIC_PARK.z)>155;
const terrain=new Terrain(read('terrain'),map,{modern:true});
assert.equal(terrain.platformAt(TREVES_PUBLIC_PARK.x,TREVES_PUBLIC_PARK.z),null,'Treves must have no fictional platform');
const structures=gameplayStructures(terrain);
assert(structures.filter(s=>s.kind==='gameplay').every(parkIsClear),'no fictional villa, walls, garage or fountain at original park');
assert.equal(gameplaySpawns().filter(s=>s.name===VILLA_PUBLIC_NAME).length,7,'all seven villa vehicles moved to Mandria');
assert(gameplaySpawns().filter(s=>Math.hypot(s.x-TREVES_PUBLIC_PARK.x,s.z-TREVES_PUBLIC_PARK.z)<150).length===0,'no parked vehicles remain at Treves');
const estate=map.gameplay.roads.find(r=>r.n==='Accesso Villa della Mandria');
assert(estate&&estate.p.length===3&&estate.access==='yes','Mandria estate must have a road connection');
assert.equal(report.originalBuildingsRemoved,0,'never demolish source buildings for villa');
console.log('MANDRIA_RELOCATION '+JSON.stringify({report,originalBuildings:originalBuildings.length,
 originalFootpaths:originalKeys.size,originalAreas:originalAreas.length,estateRoad:estate.p}));
console.log('PASS ONE villa moved to Mandria; Parco Treves source buildings, paths, areas and natural terrain restored');
