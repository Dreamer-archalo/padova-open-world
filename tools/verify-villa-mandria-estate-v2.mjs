import assert from 'node:assert/strict';
import * as THREE from '../dist/vendor/three.module.js';
import '../dist/modern-vehicles.js';
import '../dist/airport-interactivity.js';
import '../dist/airport-flight-extras.js';
import '../dist/airport-combat-flight.js';
import '../dist/airport-military-fleet.js';
import {VILLA,areaPoint} from '../dist/gameplay-areas.js';
import {VEHICLES} from '../dist/vehicles.js';
import {hangarCatalogue} from '../dist/villa-mandria-hangar.js';
import {hangarSection} from '../dist/villa-mandria-catalog-ui.js';
import {aircraftPlaceholder} from '../dist/villa-mandria-air-preview-guard.js';
import {villaLifeUpdate} from '../dist/villa-mandria-life.js';
import {estateEnhancementUpdate,safeEstateSegments} from '../dist/villa-mandria-estate-v2.js';
const start=areaPoint(VILLA,0,175),approach=areaPoint(VILLA,0,69),gate=areaPoint(VILLA,0,51);
const messages=[];
const g={state:{started:true,x:VILLA.x,z:VILLA.z,elapsed:25},terrain:{modern:true,gameplayPatches:[{}],height:()=>0,dry:()=>true},collision:{near:()=>[]},graph:{segments:[{road:{n:'Accesso Villa della Mandria',p:[[start.x,start.z],[approach.x,approach.z],[gate.x,gate.z]]}}]},scene:new THREE.Scene(),toast:message=>messages.push(message)};
villaLifeUpdate(g,.016);estateEnhancementUpdate(g,.016);
const life=g.villaLife,extra=life.expansion;
assert(extra?.root?.parent===life.root,'expansion should inherit proximity culling and cleanup');
assert.equal(extra.barns.length,3,'every unobstructed paddock gets a stable');
assert.equal(extra.fieldTools.length,3,'every unobstructed agricultural plot gets equipment');
assert(extra.lanes>0,'add safe service-lane scenery');
assert(extra.perimeter>0,'add boundary only in verified clear segments');
assert(extra.recruits.length>=1,'add a roaming suited bodyguard');
assert(extra.escort?.car?.parent===extra.root,'moving black escort car should be visible');
assert.equal(life.people.filter(p=>p.role==='gate'&&p.obj.userData.armed).length,2,'gate guards visually armed');
assert.equal(life.cars.length,2,'do not remove original parked escort cars');
const worker=life.fields[0].worker,oldWorker=worker.obj.position.clone();
const car=extra.escort.car,oldCar=car.position.clone();
g.state.elapsed=26;estateEnhancementUpdate(g,.06);
assert(worker.obj.position.distanceTo(oldWorker)>.001,'worker must walk rather than stay permanently idle');
assert(car.position.distanceTo(oldCar)>.001,'security car must patrol rather than remain parked');
const greet=life.people.find(p=>p.role==='servant');g.state.elapsed=31;g.state.x=greet.obj.position.x;g.state.z=greet.obj.position.z;
villaLifeUpdate(g,.016);estateEnhancementUpdate(g,.016);
assert(messages.includes('Hola patron'),'servants must greet the player');
g.state.elapsed=34;villaLifeUpdate(g,.016);estateEnhancementUpdate(g,.016);
assert.equal(greet.obj.rotation.x,0,'servant returns to normal posture after bow');
const blocked={...g,scene:new THREE.Scene(),villaLife:null,collision:{near:()=>[{kind:'building',solid:true}]}};
villaLifeUpdate(blocked,.016);estateEnhancementUpdate(blocked,.016);
assert.equal(blocked.villaLife.pastures.length,0);assert.equal(blocked.villaLife.fields.length,0);
assert.equal(blocked.villaLife.expansion.barns.length,0);assert.equal(blocked.villaLife.expansion.lanes,0);
assert.equal(blocked.villaLife.expansion.perimeter,0);assert.equal(blocked.villaLife.expansion.escort,null);
assert.deepEqual(safeEstateSegments(blocked,[[0,69],[40,69]]),[]);
const air=hangarCatalogue().filter(e=>hangarSection(e.id)==='air');
assert.equal(air.length,16,'full aircraft collection must remain intact');
for(const vehicle of air){
 const fallback=aircraftPlaceholder(vehicle.id,'#b52f3d');
 assert(fallback?.startsWith('data:image/svg+xml'),vehicle.id+' missing air-specific fallback');
 const xml=decodeURIComponent(fallback.slice(fallback.indexOf(',')+1));
 assert(xml.includes('svg')&&xml.includes(VEHICLES[vehicle.id].name.slice(0,38)),vehicle.id+' missing matching name');
}
assert.equal(aircraftPlaceholder('mito'),null,'a car must never be mistaken for an aircraft');
console.log('PASS Mandria expansion '+JSON.stringify({barns:extra.barns.length,fieldTools:extra.fieldTools.length,lanes:extra.lanes,fenceSegments:extra.perimeter,bodyguards:extra.recruits.length,movingEscort:!!extra.escort,aircraftCards:air.length,sourcePreservation:'blocked layouts skipped'}));
