import assert from 'node:assert/strict';
import fs from 'node:fs';
import {LocalRespawn,respawnRegion} from './dist/local-respawn.js';
import {WaterGameplay} from './dist/water-gameplay.js';
const source=fs.readFileSync('dist/game.js','utf8');
const workflow=fs.readFileSync('.github/workflows/unified-main-preview.yml','utf8');
assert.equal(respawnRegion(0,0),'padova');
assert.equal(respawnRegion(16500,0),'riviera');
assert.equal(respawnRegion(36000,-3200),'lagoon');
const dry=x=>x<14500||x>14525;
const terrain={height:()=>0,dry:(x)=>dry(x),waterAt:x=>dry(x)?null:0,waterHeight:()=>0};
const clear=()=>true;
const points=new LocalRespawn();
assert(points.remember({x:0,z:0,y:0,yaw:0,health:100},terrain,clear,1,true));
const river=points.choose({x:14512,z:0,y:-1,health:100},terrain,clear,null,{water:true,nearRoad:()=>null});
assert(river&&respawnRegion(river.x,river.z)==='riviera','Dolo drowning must never use an old Padova checkpoint');
assert(points.remember({x:35900,z:-3200,y:0,yaw:0,health:100},terrain,clear,2,true));
const lagoon=points.choose({x:35920,z:-3200,y:-1,health:100},terrain,clear,null,{water:true});
assert(lagoon&&respawnRegion(lagoon.x,lagoon.z)==='lagoon','Venetian lagoon must use a Venetian checkpoint');
const mesh={visible:true,position:{set(){}},rotation:{set(){}}};
const car={mesh,spec:{width:2,height:1.4},health:100,yaw:0};
const swimmer={mode:'car',car,x:14512,z:0,y:-2,yaw:0,speed:4,vy:0,health:100};
const water=new WaterGameplay();
assert(water.enterVehicle(swimmer,.1));
assert(swimmer.y>=0,'Vehicle must start at water level');
for(let i=0;i<44;i++)water.stepVehicle(swimmer,.1,.1);
assert.equal(water.vehicle.sink,0,'Vehicle must float first');
for(let i=0;i<65;i++)water.stepVehicle(swimmer,.1,.1);
assert(water.vehicle.sink>.7,'Vehicle must sink gradually');
water.leaveVehicle(swimmer,.1);
assert(water.swimming&&swimmer.mode==='foot'&&swimmer.car===null,'E must let the player escape and swim');
assert(source.includes('if(enterGameplayWater(terrain.waterAt(state.x,state.z,0,state.y)))return'),
 'Water entry missing from pre-physics player motion');
assert(source.indexOf('if(enterGameplayWater(terrain.waterAt(state.x,state.z,0,state.y)))return')<
 source.indexOf('const motion=groundVehicleStep('),'Vehicle can explode before entering water');
assert(source.includes('if(enterGameplayWater(waterY))')===false,'Legacy drowning path reintroduced');
assert(source.includes('waterGame.startSwimming(state,waterY)')&&source.includes('REGION NOT LOADED'),'Swim/region error paths missing');
assert(workflow.includes('cancel-in-progress: false'),'Build is still cancelled by each new code change');
console.log('PASS local Brenta/Venice respawn, float/sink, E swim, pre-crash water priority, unclogged preview.');
